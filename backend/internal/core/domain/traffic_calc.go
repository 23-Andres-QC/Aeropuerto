package domain

import (
	"math"
	"sort"
	"time"
)

// The computation of the traffic aggregates follows Part III of the methodology
// (Modelo/Insights Modelo/historico) step by step, so the two give the same
// stays and the same counts: the positions of each person are consolidated into one per
// 0.2 s instant (weighted by the detector's confidence) and physically impossible spikes are
// dropped; each position gets the zone it falls in (an INTERIOR zone first, then the smallest);
// consecutive positions in one zone make a stay, and an exit shorter than the tolerance is noise.
// A test with a case generated by the Python code itself keeps them aligned.

// TrafficAlgo holds the fixed parameters of the computation (the ones of config_insights.json).
type TrafficAlgo struct {
	StepS       float64
	MaxSpeedMps float64
	ToleranceS  float64
}

// DefaultTrafficAlgo is what Part III uses.
var DefaultTrafficAlgo = TrafficAlgo{StepS: 0.2, MaxSpeedMps: 4, ToleranceS: 1}

// TrafficSample is one stored position of a person; T is seconds since the session's start and
// Speed is NaN when the model gave none.
type TrafficSample struct {
	T, X, Y, Confidence, Speed float64
}

// TrafficPerson is every stored position of one person, in the order they were stored.
type TrafficPerson struct {
	ID      string
	Samples []TrafficSample
}

// TrafficZone is a zone of the plan as the computation needs it.
type TrafficZone struct {
	ID      int
	LocalID *int
	Type    string
	// AreaM2 is the area rounded to two decimals, as the web and Part III see it: it only orders the zones.
	AreaM2  float64
	Polygon [][2]float64
}

// TrafficInput is a session to compute.
type TrafficInput struct {
	// Start is the session's recording start; the stays' times are counted from it.
	Start  time.Time
	People []TrafficPerson
	Zones  []TrafficZone
	Params TrafficParams
	Algo   TrafficAlgo
}

// TrafficStay is a continuous stretch of one person inside one zone (Zone -1: outside every zone).
type TrafficStay struct {
	Zone       int
	Start, End float64
	Confidence float64
}

// Duration is the length of the stay in seconds.
func (s TrafficStay) Duration() float64 { return s.End - s.Start }

type position struct {
	t, x, y, speed, conf float64
	zone                 int
}

// consolidate joins the simultaneous observations of a person (several cameras) into one position per
// instant of step seconds, weighting by confidence, and drops the isolated positions that would need a
// speed above maxSpeed to reach and to leave.
func consolidate(samples []TrafficSample, step, maxSpeed float64) []position {
	type acc struct {
		wx, wy, wt, w, speed, conf float64
		speedN, n                  int
	}
	groups := map[int64]*acc{}
	for _, s := range samples {
		k := int64(math.Floor(s.T / step))
		a := groups[k]
		if a == nil {
			a = &acc{}
			groups[k] = a
		}
		w := math.Max(s.Confidence, 1e-3)
		a.wx += w * s.X
		a.wy += w * s.Y
		a.wt += w * s.T
		a.w += w
		a.conf += s.Confidence
		a.n++
		if !math.IsNaN(s.Speed) {
			a.speed += s.Speed
			a.speedN++
		}
	}
	keys := make([]int64, 0, len(groups))
	for k := range groups {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	out := make([]position, 0, len(keys))
	for _, k := range keys {
		a := groups[k]
		p := position{t: a.wt / a.w, x: a.wx / a.w, y: a.wy / a.w, conf: a.conf / float64(a.n), speed: math.NaN(), zone: -1}
		if a.speedN > 0 {
			p.speed = a.speed / float64(a.speedN)
		}
		out = append(out, p)
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].t < out[j].t })
	return dropSpikes(out, maxSpeed)
}

// dropSpikes removes, in up to three passes, the positions that are an isolated physically impossible peak.
func dropSpikes(p []position, maxSpeed float64) []position {
	for pass := 0; pass < 3; pass++ {
		n := len(p)
		if n < 3 {
			break
		}
		v := make([]float64, n-1)
		for i := range v {
			v[i] = math.Hypot(p[i+1].x-p[i].x, p[i+1].y-p[i].y) / math.Max(p[i+1].t-p[i].t, 1e-3)
		}
		kept := make([]position, 0, n)
		for i := range p {
			if i >= 1 && i <= n-2 && v[i-1] > maxSpeed && v[i] > maxSpeed {
				continue
			}
			kept = append(kept, p[i])
		}
		if len(kept) == n {
			break
		}
		p = kept
	}
	return p
}

// zoneOrder sorts zones the way a position picks its zone: INTERIOR first, then the smallest area.
func zoneOrder(zones []TrafficZone) []TrafficZone {
	ordered := append([]TrafficZone(nil), zones...)
	sort.SliceStable(ordered, func(i, j int) bool {
		a, b := ordered[i], ordered[j]
		if ai, bi := a.Type != "INTERIOR", b.Type != "INTERIOR"; ai != bi {
			return !ai
		}
		if a.AreaM2 != b.AreaM2 {
			return a.AreaM2 < b.AreaM2
		}
		return a.ID < b.ID
	})
	return ordered
}

// covers reports whether the point is inside the polygon or on its edge (like ST_Covers).
func covers(poly [][2]float64, x, y float64) bool {
	const tolerance = 1e-6
	inside := false
	n := len(poly)
	for i := 0; i < n; i++ {
		x1, y1 := poly[i][0], poly[i][1]
		x2, y2 := poly[(i+1)%n][0], poly[(i+1)%n][1]
		if (y1 > y) != (y2 > y) && x < (x2-x1)*(y-y1)/(y2-y1)+x1 {
			inside = !inside
		}
		dx, dy := x2-x1, y2-y1
		length2 := dx*dx + dy*dy
		u := 0.0
		if length2 > 0 {
			u = math.Min(1, math.Max(0, ((x-x1)*dx+(y-y1)*dy)/length2))
		}
		if math.Hypot(x1+u*dx-x, y1+u*dy-y) <= tolerance {
			return true
		}
	}
	return inside
}

// PolygonCovers reports whether the point is inside the polygon or on its edge.
func PolygonCovers(poly [][2]float64, x, y float64) bool { return covers(poly, x, y) }

// zoneAt is the zone of a position among zones already in zoneOrder (-1 when it is in none).
func zoneAt(ordered []TrafficZone, x, y float64) int {
	for _, z := range ordered {
		if covers(z.Polygon, x, y) {
			return z.ID
		}
	}
	return -1
}

type run struct{ zone, a, b int }

// stays splits a person's consolidated positions into stays. Two stays in the same zone separated by
// less than the tolerance are one (someone grazing the border does not leave and come back); and a stay
// in an INTERIOR zone shorter than the tolerance joins the neighbouring stay (walking along the front of
// a store is not a visit).
func stays(p []position, step, tolerance float64, interiors map[int]bool) []TrafficStay {
	if len(p) == 0 {
		return nil
	}
	var runs []run
	start := 0
	for i := 1; i <= len(p); i++ {
		if i == len(p) || p[i].zone != p[i-1].zone {
			runs = append(runs, run{p[start].zone, start, i})
			start = i
		}
	}
	for merged := true; merged && len(runs) >= 3; {
		merged = false
		for i := 1; i < len(runs)-1; i++ {
			before, after := runs[i-1], runs[i+1]
			if before.zone == after.zone && p[after.a].t-p[before.b-1].t-step < tolerance {
				runs = append(runs[:i-1], append([]run{{before.zone, before.a, after.b}}, runs[i+2:]...)...)
				merged = true
				break
			}
		}
	}
	brief := func(r run) bool { return interiors[r.zone] && p[r.b-1].t+step-p[r.a].t < tolerance }
	for i := 0; len(runs) > 1 && i < len(runs); {
		switch {
		case !brief(runs[i]):
			i++
		case i == 0:
			runs = append([]run{{runs[1].zone, runs[0].a, runs[1].b}}, runs[2:]...)
		default:
			runs[i-1].b = runs[i].b
			runs = append(runs[:i], runs[i+1:]...)
			if i < len(runs) && runs[i].zone == runs[i-1].zone {
				runs[i-1].b = runs[i].b
				runs = append(runs[:i], runs[i+1:]...)
			}
		}
	}
	out := make([]TrafficStay, 0, len(runs))
	for _, r := range runs {
		conf := 0.0
		for _, q := range p[r.a:r.b] {
			conf += q.conf
		}
		out = append(out, TrafficStay{Zone: r.zone, Start: p[r.a].t, End: p[r.b-1].t + step, Confidence: conf / float64(r.b-r.a)})
	}
	return out
}

// PersonStays computes the stays of one person (the unit Part III's events are built from).
func PersonStays(samples []TrafficSample, zones []TrafficZone, algo TrafficAlgo) []TrafficStay {
	ordered := zoneOrder(zones)
	interiors := map[int]bool{}
	for _, z := range zones {
		if z.Type == "INTERIOR" {
			interiors[z.ID] = true
		}
	}
	p := consolidate(samples, algo.StepS, algo.MaxSpeedMps)
	for i := range p {
		p[i].zone = zoneAt(ordered, p[i].x, p[i].y)
	}
	return stays(p, algo.StepS, algo.ToleranceS, interiors)
}

type bucketKey struct {
	zone, minutes int
	start         int64
}

type bucketAcc struct {
	people map[int]uint8 // person → bit 1: stopped, bit 2: interested
	visits int
	sum    float64
	bins   []int
}

// TrafficAccumulator adds stays to the windows of every zone. The computation from real positions and the
// generator of simulated traffic both go through it, so they count the same way and agree across windows.
type TrafficAccumulator struct {
	params  TrafficParams
	types   map[int]string
	buckets map[bucketKey]*bucketAcc
}

func NewTrafficAccumulator(params TrafficParams, zones []TrafficZone) *TrafficAccumulator {
	if params.Version == 0 {
		params = DefaultTrafficParams
	}
	a := &TrafficAccumulator{params: params, types: map[int]string{}, buckets: map[bucketKey]*bucketAcc{}}
	for _, z := range zones {
		a.types[z.ID] = z.Type
	}
	return a
}

// AddStay counts a stay of a person (any distinct number) in a zone that started at the unix second start and lasted
// duration seconds. A stay in a zone the accumulator does not know is ignored.
func (a *TrafficAccumulator) AddStay(person, zone int, start int64, duration float64) bool {
	kind, ok := a.types[zone]
	if !ok {
		return false
	}
	th := a.params.For(kind)
	var flags uint8
	if duration >= th.StopS {
		flags |= 1
	}
	if duration >= th.InterestedS {
		flags |= 2
	}
	for _, m := range TrafficWindows {
		k := bucketKey{zone: zone, minutes: m, start: floorDiv(start, int64(m)*60) * int64(m) * 60}
		b := a.buckets[k]
		if b == nil {
			b = &bucketAcc{people: map[int]uint8{}, bins: make([]int, len(DwellEdgesS)+1)}
			a.buckets[k] = b
		}
		b.people[person] |= flags
		b.visits++
		b.sum += duration
		b.bins[DwellBin(duration)]++
	}
	return true
}

// Buckets are the windows counted so far, ordered by zone, window and start.
func (a *TrafficAccumulator) Buckets() []TrafficBucket {
	out := make([]TrafficBucket, 0, len(a.buckets))
	for k, b := range a.buckets {
		tb := TrafficBucket{ZoneID: k.zone, Minutes: k.minutes, Start: time.Unix(k.start, 0).UTC(), People: len(b.people), Visits: b.visits,
			DwellSumS: b.sum, DwellBins: b.bins}
		for _, flags := range b.people {
			if flags&1 != 0 {
				tb.Stops++
			}
			if flags&2 != 0 {
				tb.Engaged++
			}
		}
		out = append(out, tb)
	}
	sort.Slice(out, func(i, j int) bool {
		x, y := out[i], out[j]
		if x.ZoneID != y.ZoneID {
			return x.ZoneID < y.ZoneID
		}
		if x.Minutes != y.Minutes {
			return x.Minutes < y.Minutes
		}
		return x.Start.Before(y.Start)
	})
	return out
}

type cellKey struct {
	hour   int64
	cx, cy int
}

type cellAcc struct {
	seconds float64
	people  int
}

// SortHeat orders heat cells by hour and position.
func SortHeat(heat []HeatCell) {
	sort.Slice(heat, func(i, j int) bool {
		a, b := heat[i], heat[j]
		if !a.Hour.Equal(b.Hour) {
			return a.Hour.Before(b.Hour)
		}
		if a.CX != b.CX {
			return a.CX < b.CX
		}
		return a.CY < b.CY
	})
}

// ComputeTraffic computes the aggregates of one session: the stays of every person per zone and window,
// and the heat cells per hour.
func ComputeTraffic(in TrafficInput) TrafficResult {
	if in.Algo.StepS <= 0 {
		in.Algo = DefaultTrafficAlgo
	}
	ordered := zoneOrder(in.Zones)
	interiors := map[int]bool{}
	for _, z := range in.Zones {
		if z.Type == "INTERIOR" {
			interiors[z.ID] = true
		}
	}
	acc := NewTrafficAccumulator(in.Params, in.Zones)
	start := in.Start.Unix()
	cells := map[cellKey]*cellAcc{}
	var res TrafficResult
	for idx, person := range in.People {
		p := consolidate(person.Samples, in.Algo.StepS, in.Algo.MaxSpeedMps)
		if len(p) == 0 {
			continue
		}
		res.People++
		res.Samples += len(p)
		seen := map[cellKey]bool{}
		for i := range p {
			p[i].zone = zoneAt(ordered, p[i].x, p[i].y)
			k := cellKey{hour: floorDiv(start+int64(math.Floor(p[i].t)), 3600) * 3600, cx: int(math.Floor(p[i].x)), cy: int(math.Floor(p[i].y))}
			c := cells[k]
			if c == nil {
				c = &cellAcc{}
				cells[k] = c
			}
			c.seconds += in.Algo.StepS
			if !seen[k] {
				seen[k] = true
				c.people++
			}
		}
		for _, s := range stays(p, in.Algo.StepS, in.Algo.ToleranceS, interiors) {
			if acc.AddStay(idx, s.Zone, start+int64(math.Floor(s.Start)), s.Duration()) {
				res.Stays++
			}
		}
	}
	res.Buckets = acc.Buckets()
	for k, c := range cells {
		res.Heat = append(res.Heat, HeatCell{Hour: time.Unix(k.hour, 0).UTC(), CX: k.cx, CY: k.cy, Seconds: c.seconds, People: c.people})
	}
	SortHeat(res.Heat)
	return res
}

// floorDiv is the integer division that rounds toward minus infinity.
func floorDiv(a, b int64) int64 {
	q := a / b
	if a%b != 0 && (a < 0) != (b < 0) {
		q--
	}
	return q
}
